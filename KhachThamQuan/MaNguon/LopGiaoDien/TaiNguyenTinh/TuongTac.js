const languageSelect = document.querySelector("#language-select");
const placesGrid = document.querySelector("#places-grid");
const emptyState = document.querySelector("#empty-state");
const searchInput = document.querySelector("#search-input");
const resultsCount = document.querySelector("#results-count");
const audioPlayer = document.querySelector("#audio-player");
const toast = document.querySelector("#toast");
const savedPlaces = new Set(JSON.parse(localStorage.getItem("visitor-guide-saved") || "[]"));
let language = languageSelect.value;
let activeCategory = "";
let showSavedOnly = false;
let currentLandmark = null;
let toastTimeout;
let searchTimeout;

function text(key) {
  return translations[language][key];
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    "\"": "&quot;",
    "'": "&#39;"
  })[character]);
}

function applyTranslations() {
  document.documentElement.lang = language;
  document.querySelector("#language-picker").setAttribute("aria-label", text("languageLabel"));
  document.querySelector("#saved-button").setAttribute("aria-label", showSavedOnly ? text("savedOnly") : text("allPlaces"));
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = text(element.dataset.i18n);
    if (value.includes("<")) element.innerHTML = value;
    else element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.placeholder = text(element.dataset.i18nPlaceholder);
  });
  document.querySelectorAll(".filter-chip").forEach(chip => {
    const key = {
      "": "filterAll",
      "Văn hóa": "filterCulture",
      "Ẩm thực": "filterFood",
      "Lịch sử": "filterHistory",
      "Kiến trúc": "filterArchitecture"
    }[chip.dataset.category];
    if (key) {
      const count = chip.querySelector("span");
      chip.textContent = text(key);
      if (count) chip.append(count);
    }
  });
  document.querySelector(".sort-label").innerHTML = text("sortLabel");
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(toastTimeout);
  toastTimeout = setTimeout(() => toast.classList.remove("show"), 2800);
}

function categoryLabel(category) {
  return ({
    "Văn hóa": text("filterCulture"),
    "Ẩm thực": text("filterFood"),
    "Lịch sử": text("filterHistory"),
    "Kiến trúc": text("filterArchitecture")
  })[category] || category;
}

function cardMarkup(place) {
  const saved = savedPlaces.has(place.id);
  const tags = place.highlights.slice(0, 2).map(tag =>
    `<span class="card-tag">${escapeHtml(tag)}</span>`).join("");
  return `
    <article class="place-card">
      <div class="place-image-wrap">
        <img class="place-image" src="${escapeHtml(place.imageUrl)}" alt="${escapeHtml(place.name)}" style="object-position:${escapeHtml(place.imagePosition)}" loading="lazy" />
        <span class="image-wash"></span>
        <span class="place-category">${escapeHtml(categoryLabel(place.category))}</span>
        <a class="image-source" href="${escapeHtml(place.imageSourceUrl)}" target="_blank" rel="noopener noreferrer" aria-label="${escapeHtml(text("imageSource"))}: ${escapeHtml(place.name)}">${text("imageSource")}</a>
        <button class="save-place${saved ? " saved" : ""}" data-save="${escapeHtml(place.id)}" aria-label="${saved ? text("removeSavedPlace") : text("savePlace")}">
          <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M20.8 8.8c0 4.5-8.8 10-8.8 10s-8.8-5.5-8.8-10A4.8 4.8 0 0 1 12 6.1a4.8 4.8 0 0 1 8.8 2.7Z"/></svg>
        </button>
        <span class="image-distance"><span></span>${escapeHtml(place.province.toLocaleUpperCase(language))}</span>
      </div>
      <div class="card-content">
        <div class="card-topline"><span>${place.reviewCount.toLocaleString(language)} ${language === "vi" ? "đánh giá" : language === "fr" ? "avis" : "reviews"}</span><span class="rating"><span>★</span>${place.rating.toFixed(1)}</span></div>
        <h3 class="place-title">${escapeHtml(place.name)}</h3>
        <p class="place-description">${escapeHtml(place.description)}</p>
        <div class="card-tags">${tags}</div>
        <div class="card-actions">
          <span class="card-meta"><svg viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="9"/><path d="M12 7v5l3 2"/></svg>${place.durationMinutes} ${text("duration")}</span>
          <button class="listen-button" data-listen="${escapeHtml(place.id)}"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M8 5v14l11-7z"/></svg>${text("listen")}</button>
        </div>
      </div>
    </article>`;
}

function renderPlaces(places) {
  emptyState.querySelector("h3").textContent = text("emptyTitle");
  emptyState.querySelector("p").textContent = text("emptyCopy");
  placesGrid.innerHTML = places.map(cardMarkup).join("");
  placesGrid.hidden = places.length === 0;
  emptyState.hidden = places.length !== 0;
  resultsCount.textContent = `${String(places.length).padStart(2, "0")} ${text("locations")}`;
}

async function loadPlaces() {
  const params = new URLSearchParams({ language });
  if (activeCategory) params.set("category", activeCategory);
  if (searchInput.value.trim()) params.set("search", searchInput.value.trim());

  try {
    const response = await fetch(`/api/landmarks?${params}`, { cache: "no-store" });
    if (!response.ok) throw new Error(`Request failed with status ${response.status}`);
    let places = await response.json();
    if (showSavedOnly) places = places.filter(place => savedPlaces.has(place.id));
    renderPlaces(places);
  } catch (error) {
    console.error("Failed to load landmarks.", error);
    placesGrid.hidden = true;
    emptyState.hidden = false;
    emptyState.querySelector("h3").textContent = text("loadError");
    emptyState.querySelector("p").textContent = "";
    resultsCount.textContent = "—";
  }
}

async function startNarration(id) {
  if (!("speechSynthesis" in window) || !("SpeechSynthesisUtterance" in window)) {
    showToast(text("speechUnavailable"));
    return;
  }

  try {
    const response = await fetch(`/api/landmarks/${encodeURIComponent(id)}?language=${language}`);
    if (!response.ok) throw new Error(`Request failed with status ${response.status}`);
    const place = await response.json();
    window.speechSynthesis.cancel();
    currentLandmark = place;
    document.querySelector("#player-title").textContent = place.name;
    document.querySelector("#player-language").textContent = text("languageNames")[language];
    document.querySelector("#player-art").style.backgroundImage = `url("${place.imageUrl}")`;
    audioPlayer.hidden = false;
    audioPlayer.classList.remove("paused");
    document.querySelector("#play-toggle").textContent = "Ⅱ";
    const narration = new SpeechSynthesisUtterance(place.description);
    narration.lang = language === "vi" ? "vi-VN" : language === "fr" ? "fr-FR" : "en-US";
    narration.onend = () => {
      if (currentLandmark?.id === place.id) audioPlayer.classList.add("paused");
    };
    narration.onerror = event => {
      if (event.error !== "canceled" && event.error !== "interrupted") showToast(text("speechError"));
    };
    window.speechSynthesis.speak(narration);
  } catch (error) {
    console.error("Failed to start narration.", error);
    showToast(text("detailError"));
  }
}

function toggleSaved(id) {
  if (savedPlaces.has(id)) {
    savedPlaces.delete(id);
    showToast(text("unsaved"));
  } else {
    savedPlaces.add(id);
    showToast(text("saved"));
  }
  localStorage.setItem("visitor-guide-saved", JSON.stringify([...savedPlaces]));
  loadPlaces();
}

document.querySelectorAll(".filter-chip").forEach(chip => {
  chip.addEventListener("click", () => {
    activeCategory = chip.dataset.category;
    document.querySelectorAll(".filter-chip").forEach(item => item.classList.toggle("selected", item === chip));
    loadPlaces();
  });
});

placesGrid.addEventListener("click", event => {
  const saveButton = event.target.closest("[data-save]");
  if (saveButton) {
    toggleSaved(saveButton.dataset.save);
    return;
  }
  const listenButton = event.target.closest("[data-listen]");
  if (listenButton) startNarration(listenButton.dataset.listen);
});

searchInput.addEventListener("input", () => {
  clearTimeout(searchTimeout);
  searchTimeout = setTimeout(loadPlaces, 220);
});

languageSelect.addEventListener("change", () => {
  language = languageSelect.value;
  applyTranslations();
  loadPlaces();
  if (!audioPlayer.hidden && currentLandmark) startNarration(currentLandmark.id);
});

document.querySelector("#saved-button").addEventListener("click", event => {
  showSavedOnly = !showSavedOnly;
  event.currentTarget.classList.toggle("is-active", showSavedOnly);
  event.currentTarget.setAttribute("aria-label", showSavedOnly ? text("savedOnly") : text("allPlaces"));
  loadPlaces();
});

document.querySelector("#play-toggle").addEventListener("click", event => {
  if (window.speechSynthesis.paused) {
    window.speechSynthesis.resume();
    audioPlayer.classList.remove("paused");
    event.currentTarget.textContent = "Ⅱ";
    return;
  }
  if (window.speechSynthesis.speaking) {
    window.speechSynthesis.pause();
    audioPlayer.classList.add("paused");
    event.currentTarget.textContent = "▶";
    return;
  }
  if (currentLandmark) startNarration(currentLandmark.id);
});

document.querySelector("#player-close").addEventListener("click", () => {
  window.speechSynthesis.cancel();
  audioPlayer.hidden = true;
  currentLandmark = null;
});

document.addEventListener("keydown", event => {
  if ((event.metaKey || event.ctrlKey) && event.key.toLowerCase() === "k") {
    event.preventDefault();
    searchInput.focus();
  }
  if (event.key === "Escape" && !audioPlayer.hidden) {
    window.speechSynthesis.cancel();
    audioPlayer.hidden = true;
    currentLandmark = null;
  }
});

applyTranslations();
loadPlaces();
