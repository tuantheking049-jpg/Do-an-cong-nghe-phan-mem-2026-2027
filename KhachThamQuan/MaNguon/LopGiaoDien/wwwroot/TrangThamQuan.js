function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(toastTimeout);
  toastTimeout = setTimeout(() => toast.classList.remove("show"), 2800);
}

function setNarrationPaused(paused) {
  audioPlayer.classList.toggle("paused", paused);
  const playToggle = document.querySelector("#play-toggle");
  playToggle.textContent = paused ? "▶" : "Ⅱ";
  playToggle.setAttribute("aria-label", text(paused ? "resumeNarration" : "pauseNarration"));
}

function updateNarrationSeek() {
  const progress = currentNarrationText.length
    ? currentNarrationIndex / currentNarrationText.length
    : 0;
  narrationSeek.value = String(Math.round(progress * Number(narrationSeek.max)));
}

function speakNarrationFromPosition() {
  if (!currentNarrationText) return;
  if (currentNarrationIndex >= currentNarrationText.length) currentNarrationIndex = 0;

  const startIndex = currentNarrationIndex;
  const narration = new SpeechSynthesisUtterance(currentNarrationText.slice(startIndex));
  currentUtterance = narration;
  narration.lang = currentNarrationLanguage;
  narration.onboundary = event => {
    if (currentUtterance !== narration || isSeekingNarration || !Number.isFinite(event.charIndex)) return;
    currentNarrationIndex = Math.min(startIndex + event.charIndex, currentNarrationText.length);
    updateNarrationSeek();
  };
  narration.onend = () => {
    if (currentUtterance !== narration) return;
    currentNarrationIndex = currentNarrationText.length;
    updateNarrationSeek();
    currentUtterance = null;
    setNarrationPaused(true);
  };
  narration.onerror = event => {
    if (currentUtterance !== narration) return;
    currentUtterance = null;
    setNarrationPaused(true);
    if (event.error !== "canceled" && event.error !== "interrupted") showToast(text("speechError"));
  };

  setNarrationPaused(false);
  narrationStartTimeout = setTimeout(() => {
    narrationStartTimeout = null;
    if (currentUtterance === narration && !audioPlayer.classList.contains("paused")) {
      window.speechSynthesis.speak(narration);
    }
  }, 100);
}

function cancelNarrationPlayback() {
  currentUtterance = null;
  clearTimeout(narrationStartTimeout);
  clearTimeout(narrationPauseTimeout);
  clearTimeout(narrationResumeTimeout);
  narrationStartTimeout = null;
  narrationPauseTimeout = null;
  narrationResumeTimeout = null;
  window.speechSynthesis.cancel();
}

async function pauseNarration() {
  if (!currentUtterance) return;
  try {
    const position = await fetchJson("/api/narration/pause", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        viTriKyTu: currentNarrationIndex,
        doDaiNoiDung: currentNarrationText.length
      })
    });
    if (!currentUtterance) return;
    currentNarrationIndex = position.viTriKyTu;
  } catch (error) {
    console.error("Failed to pause narration.", error);
    showToast(text("speechError"));
    return;
  }

  clearTimeout(narrationStartTimeout);
  narrationStartTimeout = null;
  window.speechSynthesis.pause();
  setNarrationPaused(true);
  const pausedUtterance = currentUtterance;
  narrationPauseTimeout = setTimeout(() => {
    narrationPauseTimeout = null;
    if (currentUtterance === pausedUtterance && !window.speechSynthesis.paused) {
      cancelNarrationPlayback();
      setNarrationPaused(true);
    }
  }, 250);
}

function resumeNarration() {
  if (currentUtterance && window.speechSynthesis.paused) {
    clearTimeout(narrationPauseTimeout);
    narrationPauseTimeout = null;
    window.speechSynthesis.resume();
    setNarrationPaused(false);
    const resumedUtterance = currentUtterance;
    narrationResumeTimeout = setTimeout(() => {
      narrationResumeTimeout = null;
      if (currentUtterance === resumedUtterance && window.speechSynthesis.paused) {
        cancelNarrationPlayback();
        speakNarrationFromPosition();
      }
    }, 500);
    return;
  }
  clearTimeout(narrationResumeTimeout);
  narrationResumeTimeout = null;
  speakNarrationFromPosition();
}

async function replayNarrationFromStart() {
  if (!currentNarrationText) return;
  let position;
  try {
    position = await fetchJson("/api/narration/replay", { method: "POST" });
  } catch (error) {
    console.error("Failed to restart narration.", error);
    showToast(text("speechError"));
    return;
  }
  cancelNarrationPlayback();
  currentNarrationIndex = position.viTriKyTu;
  updateNarrationSeek();
  setNarrationPaused(true);
  speakNarrationFromPosition();
}

