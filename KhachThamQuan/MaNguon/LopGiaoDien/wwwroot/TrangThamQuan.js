async function loadPlaces() {
  const params = new URLSearchParams({ language });
  if (activeCategory) params.set("category", activeCategory);
  if (searchInput.value.trim()) params.set("search", searchInput.value.trim());

  try {
    const response = await fetch(`/api/landmarks?${params}`, { cache: "no-store" });
    if (!response.ok) throw new Error(`Request failed with status ${response.status}`);
    let places = await response.json();
    if (showSavedOnly) places = places.filter(place => savedPlaces.has(place.id));
    renderPlaces(places);
  } catch (error) {
    console.error("Failed to load landmarks.", error);
    placesGrid.hidden = true;
    emptyState.hidden = false;
    emptyState.querySelector("h3").textContent = text("loadError");
    emptyState.querySelector("p").textContent = "";
    resultsCount.textContent = "—";
  }
}

async function startNarration(id) {
  if (!("speechSynthesis" in window) || !("SpeechSynthesisUtterance" in window)) {
    showToast(text("speechUnavailable"));
    return;
  }

  try {
    const narration = await fetchJson(`/api/narration/${encodeURIComponent(id)}?language=${language}`);
    const place = narration.diaDiem;
    cancelNarrationPlayback();
    currentLandmark = place;
    currentNarrationText = place.description;
    currentNarrationLanguage = narration.maGiongDoc;
    currentNarrationIndex = 0;
    updateNarrationSeek();
    document.querySelector("#player-title").textContent = place.name;
    document.querySelector("#player-language").textContent = text("languageNames")[language];
    document.querySelector("#player-art").style.backgroundImage = `url("${place.imageUrl}")`;
    audioPlayer.hidden = false;
    speakNarrationFromPosition();
  } catch (error) {
    console.error("Failed to start narration.", error);
    showToast(text("detailError"));
  }
}

