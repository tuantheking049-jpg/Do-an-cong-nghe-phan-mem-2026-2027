narrationSeek.addEventListener("change", () => {
  const progress = Number(narrationSeek.value) / Number(narrationSeek.max);
  const targetIndex = Math.round(progress * currentNarrationText.length);
  isSeekingNarration = false;

  if (!currentNarrationText) return;
  cancelNarrationPlayback();
  currentNarrationIndex = targetIndex;
  updateNarrationSeek();
  if (targetIndex < currentNarrationText.length) {
    speakNarrationFromPosition();
  } else {
    setNarrationPaused(true);
  }
});

